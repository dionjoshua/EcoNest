    public void showStock(List<Product> products) {
        rows = products;
        stockModel.setRowCount(0);
        for (Product p : products) {
            stockModel.addRow(new Object[]{p.getName(), p.getCategory(), p.getQuantity(), p.getReorderLevel(), p.getStockStatus()});
        }
    }

    public void showHistory(List<StockEntry> entries) {
        historyModel.setRowCount(0);
        for (StockEntry e : entries) {
            historyModel.addRow(new Object[]{e.getReceivedDate(), e.getProductName(), "+" + e.getQuantity(), e.getSupplier(), e.getNote()});
        }
    }

    public Product getSelectedProduct() {
        int row = tblStock.getSelectedRow();
        return row >= 0 && row < rows.size() ? rows.get(row) : null;
    }

    // keeps the same product selected after the table is reloaded
    public void selectProduct(int productId) {
        for (int i = 0; i < rows.size(); i++) {
            if (rows.get(i).getId() == productId) {
                tblStock.setRowSelectionInterval(i, i);
                return;
            }
        }
        showSelected(null);
    }

    public void showSelected(Product p) {
        boolean selected = p != null;
        lblSelected.setText(selected ? p.getName() : "Select a product");
        lblOnHand.setText(selected ? p.getQuantity() + " on hand, reorder at " + p.getReorderLevel() : "Click a row in the table");
        txtReorder.setText(selected ? String.valueOf(p.getReorderLevel()) : "");
        txtStockQty.setText("");
        txtNote.setText("");
        btnReceive.setEnabled(selected);
        btnSaveReorder.setEnabled(selected);
    }


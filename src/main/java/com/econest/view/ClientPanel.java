    // households don't have a separate contact person
    private void typeChanged() {
        boolean office = getClientType() == ClientType.OFFICE;
        lblName.setText(office ? "Company name" : "Full name");
        txtContactPerson.setEnabled(office);
        if (!office) {
            txtContactPerson.setText("");
        }
    }

    public void showClients(List<Client> clients) {
        rows = clients;
        model.setRowCount(0);
        for (Client c : clients) {
            String contact = c instanceof OfficeClient ? ((OfficeClient) c).getContactPerson() : "";
            model.addRow(new Object[]{c.getName(), c.getType(), contact, c.getPhone(), c.getEmail(), c.getAddress()});
        }
    }

    public Client getSelectedClient() {
        int row = tblClients.getSelectedRow();
        return row >= 0 && row < rows.size() ? rows.get(row) : null;
    }

    public void fillForm(Client c) {
        lblFormTitle.setText("Edit client");
        cmbType.setSelectedItem(c.getType());
        txtName.setText(c.getName());
        txtContactPerson.setText(c instanceof OfficeClient ? ((OfficeClient) c).getContactPerson() : "");
        txtPhone.setText(c.getPhone());
        txtEmail.setText(c.getEmail());
        txtAddress.setText(c.getAddress());
        btnAdd.setEnabled(false);
        btnUpdate.setEnabled(true);
        btnRemove.setEnabled(true);
    }

    public void clearForm() {
        lblFormTitle.setText("New client");
        cmbType.setSelectedIndex(0);
        txtName.setText("");
        txtContactPerson.setText("");
        txtPhone.setText("");
        txtEmail.setText("");
        txtAddress.setText("");
        tblClients.clearSelection();
        btnAdd.setEnabled(true);
        btnUpdate.setEnabled(false);
        btnRemove.setEnabled(false);
    }

    public ClientType getClientType() {
        return (ClientType) cmbType.getSelectedItem();
    }

